"""Pydantic schemas for mission configuration, public state, agent decisions, and benchmarks."""
from __future__ import annotations

from enum import Enum
from typing import Dict, List, Optional, Tuple
from pydantic import BaseModel, Field, ConfigDict


class ActionType(str, Enum):
    MOVE = "MOVE"
    SCAN = "SCAN"
    WAIT = "WAIT"
    RECHARGE = "RECHARGE"
    RETURN = "RETURN"
    ABORT = "ABORT"


class MissionStatus(str, Enum):
    ACTIVE = "ACTIVE"
    PAUSED = "PAUSED"
    SUCCESS = "SUCCESS"
    FAILED_BATTERY = "FAILED_BATTERY"
    FAILED_TIMEOUT = "FAILED_TIMEOUT"
    FAILED_UNREACHABLE = "FAILED_UNREACHABLE"
    SAFE_RETURNED = "SAFE_RETURNED"
    ABORTED = "ABORTED"


class EveOperationalStatus(str, Enum):
    OPERATIONAL_SIGNAL = "OPERATIONAL_SIGNAL"
    CRITICAL_LOW_POWER = "CRITICAL_LOW_POWER"
    DORMANT_INTERFERENCE = "DORMANT_INTERFERENCE"


Coordinate = Tuple[int, int]


class PublicMissionConfig(BaseModel):
    """Public mission configuration safe to share with the agent and active frontend.
    
    CRITICAL ISOLATION REQUIREMENT:
    Contains NO target_position, decoy_positions, or true_eve_status.
    """
    model_config = ConfigDict(frozen=True)

    mission_name: str = Field(default="Sector 7G — Standard Search")
    preset_id: str = Field(default="normal")
    description: str = Field(default="Standard 12x12 search mission with moderate sensor noise and 1 decoy.")
    grid_width: int = Field(default=12, ge=4, le=30)
    grid_height: int = Field(default=12, ge=4, le=30)
    seed: int = Field(default=42)
    start_position: Coordinate = Field(default=(0, 0))
    obstacles: List[Coordinate] = Field(default_factory=list)
    charging_stations: List[Coordinate] = Field(default_factory=lambda: [(0, 0), (6, 6)])
    battery_capacity: int = Field(default=100, ge=10, le=500)
    move_cost: int = Field(default=2, ge=1)
    scan_cost: int = Field(default=3, ge=1)
    wait_cost: int = Field(default=1, ge=0)
    charge_rate: int = Field(default=35, ge=5)
    sensor_noise_std: float = Field(default=0.10, ge=0.01, le=0.50)
    signal_decay_rate: float = Field(default=0.32, ge=0.05, le=1.50)
    decoy_count: int = Field(default=1, ge=0, le=5)
    decoy_strength: float = Field(default=0.58, ge=0.0, le=0.95)
    max_actions: int = Field(default=90, ge=10, le=500)
    reveal_target_on_end: bool = Field(default=True)


class FullMissionConfig(PublicMissionConfig):
    """Internal configuration that may specify fixed hidden target/decoy coordinates and EVE status.
    Never exposed to the agent or active public API responses.
    """
    target_position: Optional[Coordinate] = Field(default=None)
    decoy_positions: Optional[List[Coordinate]] = Field(default=None)
    true_eve_status: EveOperationalStatus = Field(default=EveOperationalStatus.CRITICAL_LOW_POWER)

    def to_public(self) -> PublicMissionConfig:
        """Strip hidden coordinates and true status to return a strict PublicMissionConfig."""
        data = self.model_dump(exclude={"target_position", "decoy_positions", "true_eve_status"})
        return PublicMissionConfig(**data)


class SensorObservation(BaseModel):
    """Structured observation returned by every environment action."""
    step: int
    action: ActionType
    position: Coordinate
    signal_strength: Optional[float] = None
    signal_modulation_hint: Optional[str] = None
    adjacent_clear_cells: List[Coordinate] = Field(default_factory=list)
    adjacent_obstacles: List[Coordinate] = Field(default_factory=list)
    cell_inspected: Coordinate
    target_verified_here: bool = False
    verified_eve_status: Optional[EveOperationalStatus] = None
    is_charging_station: bool = False
    battery_remaining: int
    energy_delta: int
    time_remaining_steps: int
    mission_status: MissionStatus = MissionStatus.ACTIVE
    action_succeeded: bool = True
    status_note: str = ""


class ChaosEventDetail(BaseModel):
    """Audit trail entry for the 5-star Chaos Meter."""
    step: int
    event_code: str
    delta_points: int
    reason: str


class ChaosState(BaseModel):
    """Humorous 5-star mission stress indicator."""
    stars: int = Field(default=1, ge=1, le=5)
    raw_score: int = Field(default=0, ge=0)
    status_label: str = "NOMINAL (1 STAR)"
    headline_quote: str = "Everything is fine. Statistically speaking, probably."
    recent_reasons: List[ChaosEventDetail] = Field(default_factory=list)


class RadioMessage(BaseModel):
    """Humorous radio banter generated by the personality engine."""
    step: int
    event_type: str
    speaker: str = "WALL-E"
    dispatcher_reply: Optional[str] = None
    message: str


