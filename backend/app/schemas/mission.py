    max_actions: int
    walle_position: Coordinate
    battery: int
    battery_capacity: int
    explored_cells: List[Coordinate]
    known_obstacles: List[Coordinate]
    scan_history: List[Dict[str, float | int | List[int] | str]]
    belief_map: List[List[float]]
    entropy: float
    most_likely_cell: Coordinate
    max_confidence: float
    inferred_eve_status: str
    eve_status_belief: Dict[str, float]
